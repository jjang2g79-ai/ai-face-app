export function getRandomResultBySpecies(species = 'human') {
  const pool = results.filter((r) => r.species === species)
  const safePool = pool.length > 0 ? pool : results.filter((r) => r.species === 'human')
  return safePool[Math.floor(Math.random() * safePool.length)]
}

// Used by analyzeImage.js to deterministically pick a result that matches the
// mood profile derived from the image hash. index maps 1:1 to MOOD_POOLS order.
export function getResultBySpeciesIndex(species = 'human', index = 0) {
  const pool = results.filter((r) => r.species === species)
  const safePool = pool.length > 0 ? pool : results.filter((r) => r.species === 'human')
  return safePool[index % safePool.length]
}

export function getRandomResult() {
  return results[Math.floor(Math.random() * results.length)]
}

